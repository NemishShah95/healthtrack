/// SchemaV1 has been on the iPhone since 2026-11-01 and holds real data. It must never change in place.
/// If this test fails you edited a V1 model: undo that, add SchemaV2 with a MigrationStage, test the
/// migration against a populated store, then add a V2 snapshot here (DATA_SAFETY.md → Safe upgrade procedure).
@Test func schemaV1IsFrozen() {
    let schema = Schema(versionedSchema: SchemaV1.self)
    let lines = schema.entities.flatMap { e in
        e.attributes.map { "\(e.name).\($0.name): \($0.valueType)" }
            + e.relationships.map { "\(e.name).\($0.name) -> \($0.destination)" }
    }.sorted()
    #expect(lines == schemaV1Snapshot, "SchemaV1 changed. Add SchemaV2 + a migration instead (see comment above).")
}

